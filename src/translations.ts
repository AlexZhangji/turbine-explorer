const phrases=Object.entries(english).sort((a,b)=>b[0].length-a[0].length);
const cache=new Map<string,string>();
export function translateEnglish(source:string) {
  if(!/[\p{Script=Han}]/u.test(source))return source;
  const cached=cache.get(source);if(cached)return cached;
  const trimmed=source.trim();
  let result=english[trimmed] ? source.replace(trimmed,english[trimmed]) : source.replace(/第([234])级涡轮动叶环/g,'Stage $1 turbine rotor').replace(/(\d+) 个入口/g,'$1 components').replace(/(\d+) 张图/g,'$1 images');
  if(!english[trimmed])for(const [zh,en] of phrases)if(result.includes(zh))result=result.split(zh).join(en);
  if(cache.size>4000)cache.clear();cache.set(source,result);return result;
}
